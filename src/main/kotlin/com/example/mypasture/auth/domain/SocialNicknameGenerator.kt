        "사슴", "치타", "까치", "백조", "제비", "나비", "악어", "표범", "물개", "낙타",
        "호랑이", "얼룩말", "코알라", "미어캣", "수리", "물소", "산양", "염소", "야크", "노루",
        "라마", "망아지", "송아지", "청설모", "족제비", "펭귄", "앵무새", "해달", "해마", "돌고래",
