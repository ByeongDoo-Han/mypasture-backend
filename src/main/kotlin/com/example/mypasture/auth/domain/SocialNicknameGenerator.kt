object SocialNicknameGenerator {
    private val adjectives = listOf(
        "친절한", "상냥한", "다정한", "씩씩한", "즐거운", "따뜻한", "용감한", "행복한", "반가운", "포근한",
        "신나는", "고마운", "명랑한", "활발한", "사랑스런", "온화한", "유쾌한", "정직한", "소중한", "순수한",
        "밝은", "고운", "착한", "멋진", "기쁜", "예쁜", "환한", "푸른", "맑은", "귀한",
        "설레는", "빛나는", "정다운", "건강한", "유순한", "느긋한", "똑똑한", "우아한", "단정한", "성실한",
        "귀여운", "넉넉한", "화목한", "기운찬", "희망찬", "활기찬", "반짝이는", "평화로운", "부지런한", "신중한",
    )
    private val animals = listOf(
        "사자", "토끼", "여우", "판다", "수달", "기린", "하마", "참새", "오리", "고래",
